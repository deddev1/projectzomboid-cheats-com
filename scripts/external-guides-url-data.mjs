/**
 * @param {string} url
 */
export function normalizeProvidedUrl(url) {
	const trimmed = url.trim();
	const u = new URL(trimmed.startsWith('http') ? trimmed : `https://${trimmed}`);
	u.hash = '';
	u.search = '';
	const host = u.hostname.toLowerCase().replace(/^www\./, '');
	return `https://${host}/`;
}

/**
 * @param {string} url
 * @returns {GameMatch}
 */
export function inferGameFromUrl(url) {
	const host = new URL(url).hostname.toLowerCase().replace(/^www\./, '');
	const label = host.replace(/\.(com|net|org|cc)$/, '');

	for (const [pattern, game] of DOMAIN_GAME_RULES) {
		if (pattern.test(label) || pattern.test(host)) return game;
	}

	throw new Error(`Cannot infer game for URL: ${url}`);
}

/**
 * @param {string} url
 */
export function slugFromUrl(url) {
	const host = new URL(url).hostname.toLowerCase().replace(/^www\./, '').replace(/\./g, '-');
	return `guide-${host}`;
}

